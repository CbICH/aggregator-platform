import { expect, test, type Page } from '@playwright/test';

const password = 'correct horse battery';

async function registerAndLogin(page: Page, email: string, role: 'candidate' | 'employer') {
  await page.goto('/register');
  await page.getByRole('radio', { name: role === 'candidate' ? 'Ищу работу' : 'Ищу специалиста' }).check();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Создать аккаунт' }).click();
  await expect(page).toHaveURL(/check-email/);
  let id = '';
  await expect.poll(async () => {
    const inbox = await (await page.request.get(`http://localhost:8025/api/v1/search?query=${encodeURIComponent(`to:${email}`)}`)).json();
    id = inbox.messages?.[0]?.ID ?? '';
    return id;
  }).not.toBe('');
  const mail = await (await page.request.get(`http://localhost:8025/api/v1/message/${id}`)).json();
  const url = String(mail.Text).match(/https?:\/\/[^\s]+\/verify-email#token=[^\s]+/)?.[0];
  expect(url).toBeTruthy();
  await page.goto(url!);
  await page.getByRole('button', { name: 'Подтвердить email' }).click();
  await page.getByRole('link', { name: 'Продолжить', exact: true }).click();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page).toHaveURL(/workspace/);
}

